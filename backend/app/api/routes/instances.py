from __future__ import annotations


from fastapi import APIRouter, HTTPException, Query
from sqlalchemy import func, or_

from app.api.deps import CurrentUser, DbSession, OperatorUser
from app.core.utils import utcnow
from app.models import InfrastructureInstance, Metric
from app.schemas.domain import InstanceCreate, InstanceOut, InstanceUpdate, MetricOut
from app.services import cost as cost_service
from app.services import monitoring
from app.services.audit import record_audit
from app.services.notifications import notify

router = APIRouter(prefix="/instances", tags=["infrastructure"])


@router.get("", response_model=list[InstanceOut])
def list_instances(
    db: DbSession,
    user: CurrentUser,
    source: str | None = None,
    environment: str | None = None,
    health: str | None = None,
    search: str | None = None,
    limit: int = Query(default=200, le=500),
) -> list[InstanceOut]:
    query = db.query(InfrastructureInstance)
    if source:
        query = query.filter(InfrastructureInstance.source == source)
    if environment:
        query = query.filter(InfrastructureInstance.environment == environment)
    if health:
        query = query.filter(InfrastructureInstance.health_status == health)
    if search:
        like = f"%{search}%"
        query = query.filter(
            or_(
                InfrastructureInstance.name.ilike(like),
                InfrastructureInstance.hostname.ilike(like),
                InfrastructureInstance.external_id.ilike(like),
            )
        )
    rows = query.order_by(InfrastructureInstance.name).limit(limit).all()
    return [InstanceOut.model_validate(row) for row in rows]


@router.get("/{instance_id}")
def get_instance(instance_id: int, db: DbSession, user: CurrentUser) -> dict:
    instance = db.get(InfrastructureInstance, instance_id)
    if instance is None:
        raise HTTPException(status_code=404, detail="Instance not found")
    latest = (
        db.query(Metric)
        .filter(Metric.instance_id == instance_id)
        .order_by(Metric.timestamp.desc())
        .first()
    )
    thresholds = monitoring.get_thresholds(db)
    alerts = []
    if latest:
        for metric_name, value in (
            ("cpu_percent", latest.cpu_percent),
            ("memory_percent", latest.memory_percent),
            ("disk_percent", latest.disk_percent),
            ("network_in_kbps", latest.network_in_kbps),
        ):
            rule = thresholds.get(metric_name)
            if not rule:
                continue
            level = monitoring.classify(value, rule.warning, rule.critical)
            if level != "healthy":
                alerts.append(
                    {
                        "metric": metric_name,
                        "display_name": rule.display_name,
                        "value": value,
                        "unit": rule.unit,
                        "level": level,
                        "threshold": rule.critical if level == "critical" else rule.warning,
                    }
                )
    stats = (
        db.query(
            func.avg(Metric.cpu_percent),
            func.avg(Metric.memory_percent),
            func.max(Metric.cpu_percent),
            func.count(Metric.id),
        )
        .filter(Metric.instance_id == instance_id)
        .one()
    )
    return {
        "instance": InstanceOut.model_validate(instance).model_dump(),
        "latest_metric": MetricOut.model_validate(latest).model_dump() if latest else None,
        "alerts": alerts,
        "statistics": {
            "avg_cpu": round(float(stats[0] or 0), 2),
            "avg_memory": round(float(stats[1] or 0), 2),
            "peak_cpu": round(float(stats[2] or 0), 2),
            "samples": int(stats[3] or 0),
        },
        "estimated_monthly_usd": instance.monthly_cost_usd,
        "data_note": (
            "Measured locally with psutil."
            if instance.source == "local"
            else "Synthetic telemetry generated by the simulator."
            if instance.source == "simulated"
            else "Imported from AWS."
        ),
    }


@router.get("/{instance_id}/metrics", response_model=list[MetricOut])
def instance_metrics(
    instance_id: int,
    db: DbSession,
    user: CurrentUser,
    hours: int = Query(default=6, ge=1, le=168),
    limit: int = Query(default=500, le=2000),
) -> list[MetricOut]:
    instance = db.get(InfrastructureInstance, instance_id)
    if instance is None:
        raise HTTPException(status_code=404, detail="Instance not found")
    from datetime import timedelta

    rows = (
        db.query(Metric)
        .filter(Metric.instance_id == instance_id, Metric.timestamp >= utcnow() - timedelta(hours=hours))
        .order_by(Metric.timestamp.desc())
        .limit(limit)
        .all()
    )
    return [MetricOut.model_validate(row) for row in reversed(rows)]


@router.post("", response_model=InstanceOut, status_code=201)
def create_instance(payload: InstanceCreate, db: DbSession, operator: OperatorUser) -> InstanceOut:
    if not payload.simulate:
        raise HTTPException(
            status_code=422,
            detail=(
                "Only simulated instances can be added from the UI. Real EC2 instances are discovered "
                "read-only through the AWS integration."
            ),
        )
    pricing = cost_service.pricing_map(db)
    rate = pricing.get(payload.instance_type)
    monthly = (
        round(rate.hourly_usd * 730 + rate.ebs_gb_usd * payload.disk_gb, 2) if rate else 0.0
    )
    instance = InfrastructureInstance(
        name=payload.name,
        provider="aws-simulated",
        source="simulated",
        instance_type=payload.instance_type,
        region=payload.region,
        environment=payload.environment,
        status="running",
        hostname=f"{payload.name}.internal",
        os_name="Ubuntu 22.04 LTS",
        cpu_cores=payload.cpu_cores,
        memory_mb=payload.memory_mb,
        disk_gb=payload.disk_gb,
        monthly_cost_usd=monthly,
        tags={**payload.tags, "role": payload.tags.get("role", "web"), "data": "simulated"},
        health_status="healthy",
        last_seen_at=utcnow(),
    )
    db.add(instance)
    db.commit()
    db.refresh(instance)
    record_audit(
        db,
        actor=operator.email,
        action="instance.created",
        entity_type="instance",
        entity_id=instance.id,
        detail={"name": instance.name, "simulated": True},
    )
    monitoring.simulate_all(db)
    return InstanceOut.model_validate(instance)


@router.patch("/{instance_id}", response_model=InstanceOut)
def update_instance(
    instance_id: int,
    payload: InstanceUpdate,
    db: DbSession,
    operator: OperatorUser,
) -> InstanceOut:
    instance = db.get(InfrastructureInstance, instance_id)
    if instance is None:
        raise HTTPException(status_code=404, detail="Instance not found")
    changes = payload.model_dump(exclude_unset=True)
    for key in ("name", "environment"):
        if key in changes and changes[key]:
            setattr(instance, key, changes[key])
    if changes.get("tags"):
        instance.tags = {**(instance.tags or {}), **changes["tags"]}
    db.commit()
    db.refresh(instance)
    record_audit(
        db,
        actor=operator.email,
        action="instance.updated",
        entity_type="instance",
        entity_id=instance.id,
        detail=changes,
    )
    return InstanceOut.model_validate(instance)


@router.post("/{instance_id}/power")
def power_action(
    instance_id: int,
    action: str,
    db: DbSession,
    operator: OperatorUser,
) -> dict:
    """Simulated power state change. Real AWS instances are never mutated."""
    if action not in {"start", "stop", "reboot"}:
        raise HTTPException(status_code=422, detail="action must be start, stop or reboot")
    instance = db.get(InfrastructureInstance, instance_id)
    if instance is None:
        raise HTTPException(status_code=404, detail="Instance not found")
    if instance.source != "simulated":
        raise HTTPException(
            status_code=403,
            detail="Power operations are only available for simulated instances; real infrastructure is read-only.",
        )
    if action == "stop":
        instance.status = "stopped"
        instance.health_status = "offline"
    else:
        instance.status = "running"
        instance.health_status = "healthy"
    db.commit()
    monitoring.simulate_all(db) if action != "stop" else db.commit()
    record_audit(
        db,
        actor=operator.email,
        action=f"instance.{action}",
        entity_type="instance",
        entity_id=instance.id,
        detail={"simulated": True},
    )
    notify(
        db,
        title=f"Instance {action} (simulated)",
        message=f"{instance.name} was set to {instance.status}. No cloud API was called.",
        severity="info",
        category="infrastructure",
        entity_type="instance",
        entity_id=instance.id,
    )
    return {"instance_id": instance.id, "status": instance.status, "simulated": True}


@router.delete("/{instance_id}")
def delete_instance(
    instance_id: int,
    db: DbSession,
    operator: OperatorUser,
) -> dict:
    instance = db.get(InfrastructureInstance, instance_id)
    if instance is None:
        raise HTTPException(status_code=404, detail="Instance not found")
    if instance.source != "simulated":
        raise HTTPException(status_code=403, detail="Only simulated inventory rows can be removed")
    name = instance.name
    db.delete(instance)
    db.commit()
    record_audit(
        db,
        actor=operator.email,
        action="instance.deleted",
        entity_type="instance",
        entity_id=instance_id,
        detail={"name": name, "simulated": True},
    )
    return {"deleted": instance_id, "name": name, "message": "Simulated inventory row removed"}
