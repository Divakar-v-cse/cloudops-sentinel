import type { ReactNode } from 'react'
import { Icon, Spinner } from './Icon'
import { healthBadge, severityBadge } from '../lib/format'

export function PageHeader({
  title,
  subtitle,
  actions,
  badge,
}: {
  title: string
  subtitle?: string
  actions?: ReactNode
  badge?: ReactNode
}) {
  return (
    <div className="mb-5 flex flex-col gap-3 sm:flex-row sm:items-start sm:justify-between">
      <div>
        <div className="flex items-center gap-2">
          <h1 className="text-xl font-semibold tracking-tight text-slate-900 dark:text-slate-50">{title}</h1>
          {badge}
        </div>
        {subtitle && <p className="mt-1 max-w-3xl text-[13px] text-slate-500 dark:text-slate-400">{subtitle}</p>}
      </div>
      {actions && <div className="flex flex-wrap items-center gap-2">{actions}</div>}
    </div>
  )
}

export function Card({
  title,
  subtitle,
  actions,
  children,
  className = '',
  bodyClassName = 'card-body',
  footer,
}: {
  title?: string
  subtitle?: string
  actions?: ReactNode
  children: ReactNode
  className?: string
  bodyClassName?: string
  footer?: ReactNode
}) {
  return (
    <section className={`card ${className}`}>
      {(title || actions) && (
        <div className="card-header">
          <div>
            {title && <h2 className="card-title">{title}</h2>}
            {subtitle && <p className="card-subtitle">{subtitle}</p>}
          </div>
          {actions && <div className="flex shrink-0 items-center gap-2">{actions}</div>}
        </div>
      )}
      <div className={bodyClassName}>{children}</div>
      {footer && <div className="border-t px-5 py-3 text-xs text-slate-500 dark:text-slate-400">{footer}</div>}
    </section>
  )
}

export function StatCard({
  label,
  value,
  hint,
  icon,
  tone = 'default',
  onClick,
}: {
  label: string
  value: ReactNode
  hint?: ReactNode
  icon?: string
  tone?: 'default' | 'success' | 'warning' | 'critical' | 'info'
  onClick?: () => void
}) {
  const tones: Record<string, string> = {
    default: 'text-slate-500 bg-slate-100 dark:bg-slate-800 dark:text-slate-300',
    success: 'text-emerald-600 bg-emerald-500/10',
    warning: 'text-amber-600 bg-amber-500/10',
    critical: 'text-rose-600 bg-rose-500/10',
    info: 'text-brand-600 bg-brand-500/10',
  }
  return (
    <div
      className={`card p-4 ${onClick ? 'cursor-pointer transition-shadow hover:shadow-md' : ''}`}
      onClick={onClick}
      role={onClick ? 'button' : undefined}
      tabIndex={onClick ? 0 : undefined}
      onKeyDown={onClick ? (event) => event.key === 'Enter' && onClick() : undefined}
    >
      <div className="flex items-start justify-between gap-2">
        <p className="text-[11px] font-medium uppercase tracking-wide text-slate-500 dark:text-slate-400">{label}</p>
        {icon && (
          <span className={`rounded-md p-1.5 ${tones[tone]}`}>
            <Icon name={icon} size={14} />
          </span>
        )}
      </div>
      <p className="mt-2 text-2xl font-semibold tracking-tight text-slate-900 dark:text-slate-50">{value}</p>
      {hint && <p className="mt-1 text-[11.5px] leading-tight text-slate-500 dark:text-slate-400">{hint}</p>}
    </div>
  )
}

export function Badge({ children, className = 'badge badge-neutral' }: { children: ReactNode; className?: string }) {
  return <span className={className}>{children}</span>
}

export function SeverityBadge({ value }: { value: string }) {
  return <span className={severityBadge(value)}>{value}</span>
}

export function HealthBadge({ value }: { value: string }) {
  return <span className={healthBadge(value)}>{value}</span>
}

export function SourceBadge({ source }: { source?: string }) {
  if (!source) return <span className="badge badge-neutral">unknown</span>
  if (source === 'simulated')
    return (
      <span className="badge badge-medium" title="Synthetic data generated by the built-in simulator">
        simulated
      </span>
    )
  if (source === 'aws')
    return (
      <span className="badge badge-info" title="Retrieved from an authorised AWS account">
        aws
      </span>
    )
  if (source === 'local')
    return (
      <span className="badge badge-success" title="Measured on this host with psutil">
        local
      </span>
    )
  if (source === 'pipeline') return <span className="badge badge-info">pipeline</span>
  if (source === 'tool') return <span className="badge badge-info">tool</span>
  if (source === 'rule-engine') return <span className="badge badge-neutral">rule engine</span>
  return <span className="badge badge-neutral">{source}</span>
}

export function Loading({ label = 'Loading…', rows = 3 }: { label?: string; rows?: number }) {
  return (
    <div className="space-y-2 py-2" aria-busy="true" aria-label={label}>
      {Array.from({ length: rows }).map((_, index) => (
        <div
          key={index}
          className="h-9 animate-pulse rounded-md bg-slate-200/70 dark:bg-slate-800/70"
          style={{ animationDelay: `${index * 80}ms` }}
        />
      ))}
    </div>
  )
}

