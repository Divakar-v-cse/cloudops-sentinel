export function Progress({ value, tone = 'brand' }: { value: number; tone?: 'brand' | 'success' | 'warning' | 'critical' }) {
  const colors = {
    brand: 'bg-brand-500',
    success: 'bg-emerald-500',
    warning: 'bg-amber-500',
    critical: 'bg-rose-500',
  }
  return (
    <div className="h-1.5 w-full overflow-hidden rounded-full bg-slate-200 dark:bg-slate-800" role="progressbar" aria-valuenow={Math.round(value)} aria-valuemin={0} aria-valuemax={100}>
      <div className={`h-full rounded-full ${colors[tone]} transition-all`} style={{ width: `${Math.min(Math.max(value, 0), 100)}%` }} />
    </div>
  )
}

export function UsageBar({ value }: { value: number | null }) {
  if (value === null) return <span className="text-xs text-slate-400">—</span>
  const tone = value >= 90 ? 'critical' : value >= 75 ? 'warning' : 'success'
  return (
    <div className="flex min-w-[92px] items-center gap-2">
      <div className="w-16">
        <Progress value={value} tone={tone} />
      </div>
      <span className="tabular-nums text-xs text-slate-600 dark:text-slate-300">{value.toFixed(0)}%</span>
    </div>
  )
}

export function Tabs({
  tabs,
  active,
  onChange,
}: {
  tabs: { id: string; label: string; count?: number }[]
  active: string
  onChange: (id: string) => void
}) {
  return (
    <div className="flex flex-wrap gap-1 border-b pb-2" role="tablist">
      {tabs.map((tab) => (
        <button
          key={tab.id}
          role="tab"
          aria-selected={active === tab.id}
          type="button"
          onClick={() => onChange(tab.id)}
          className={`rounded-md px-3 py-1.5 text-xs font-medium transition-colors ${
            active === tab.id
              ? 'bg-brand-600 text-white'
              : 'text-slate-600 hover:bg-slate-100 dark:text-slate-300 dark:hover:bg-slate-800'
          }`}
        >
          {tab.label}
          {tab.count !== undefined && (
            <span className={`ml-1.5 rounded-full px-1.5 py-0.5 text-[10px] ${active === tab.id ? 'bg-white/20' : 'bg-slate-200 dark:bg-slate-700'}`}>
              {tab.count}
            </span>
          )}
        </button>
      ))}
    </div>
  )
}

export function Pagination({
  page,
  pages,
  total,
  onPage,
}: {
  page: number
  pages: number
  total: number
  onPage: (page: number) => void
}) {
  if (pages <= 1) {
    return <p className="text-xs text-slate-500 dark:text-slate-400">{total} record{total === 1 ? '' : 's'}</p>
  }
  return (
    <div className="flex items-center justify-between gap-3 pt-3">
      <p className="text-xs text-slate-500 dark:text-slate-400">
        Page {page} of {pages} · {total} records
      </p>
      <div className="flex gap-1">
        <button type="button" className="btn btn-secondary btn-xs" disabled={page <= 1} onClick={() => onPage(page - 1)}>
          Previous
        </button>
        <button type="button" className="btn btn-secondary btn-xs" disabled={page >= pages} onClick={() => onPage(page + 1)}>
          Next
        </button>
      </div>
    </div>
  )
}

